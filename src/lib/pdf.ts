// Direct-download PDFs built with jsPDF (no print dialog).
// Loaded lazily so jsPDF only ships when someone actually downloads a PDF.
import {
  INQUIRY_PDF_THEME,
  INSTITUTE_LOGO,
  INSTITUTE_NAME,
  type PdfTheme,
} from "@/data/institute";
import type { jsPDF } from "jspdf";

export interface ExportColumnLike<T> {
  header: string;
  value: (row: T) => string | number;
}

export interface PdfImage {
  data: string; // data URL (JPEG/PNG)
  width: number;
  height: number;
}

/** Any image URL → JPEG data URL via canvas (handles webp/gif too). Null on failure. */
export async function loadImage(url: string): Promise<PdfImage | null> {
  try {
    const res = await fetch(url);
    if (!res.ok) return null;
    const bitmap = await createImageBitmap(await res.blob());
    const canvas = document.createElement("canvas");
    canvas.width = bitmap.width;
    canvas.height = bitmap.height;
    const ctx = canvas.getContext("2d");
    if (!ctx) return null;
    ctx.fillStyle = "#FFFFFF";
    ctx.fillRect(0, 0, canvas.width, canvas.height);
    ctx.drawImage(bitmap, 0, 0);
    return {
      data: canvas.toDataURL("image/jpeg", 0.9),
      width: bitmap.width,
      height: bitmap.height,
    };
  } catch {
    return null;
  }
}

let logoCache: Promise<string | null> | null = null;

/** Logo as a data URL (cached). Resolves to null if the file is missing. */
export function loadLogo(src = INSTITUTE_LOGO) {
  logoCache ??= fetch(src)
    .then((r) => (r.ok ? r.blob() : Promise.reject()))
    .then(
      (blob) =>
        new Promise<string>((resolve, reject) => {
          const reader = new FileReader();
          reader.onload = () => resolve(String(reader.result));
          reader.onerror = reject;
          reader.readAsDataURL(blob);
        }),
    )
    .catch(() => {
      logoCache = null;
      return null;
    });
  return logoCache;
}

export async function newPdf(
  orientation: "portrait" | "landscape" = "portrait",
) {
  const { jsPDF } = await import("jspdf");
  return new jsPDF({ orientation, unit: "mm", format: "a4" });
}

export const MARGIN = 7.5;

/** Dark rounded label, e.g. "INQUIRY DETAILS". Returns the y below it. */
export function sectionPill(
  doc: jsPDF,
  text: string,
  x: number,
  y: number,
  t: PdfTheme = INQUIRY_PDF_THEME,
) {
  doc.setFont("helvetica", "bold");
  doc.setFontSize(7.5);
  const accent = t.pillAccent ? 1.4 : 0;
  const w = doc.getTextWidth(text) + 9 + accent;
  doc.setFillColor(t.pill);
  doc.roundedRect(x, y, w, 7, 1, 1, "F");
  if (t.pillAccent) {
    doc.setFillColor(t.pillAccent);
    doc.rect(x, y, accent, 7, "F");
  }
  doc.setTextColor("#FFFFFF");
  doc.text(text, x + 4.5 + accent, y + 4.7);
  return y + 7;
}

/** Bottom footer band: "Generated by …". */
export function footerBand(
  doc: jsPDF,
  name = INSTITUTE_NAME,
  t: PdfTheme = INQUIRY_PDF_THEME,
) {
  const w = doc.internal.pageSize.getWidth();
  const h = doc.internal.pageSize.getHeight();
  doc.setFillColor(t.footerBg);
  doc.rect(0, h - 13, w, 13, "F");
  doc.setFont("helvetica", "normal");
  doc.setFontSize(8);
  doc.setTextColor(t.footerText);
  doc.text(`Generated by ${name}`, w / 2, h - 5.5, { align: "center" });
}

/** Header band with logo (left) and title lines (right). Returns its bottom y. */
export function headerBand(
  doc: jsPDF,
  logo: string | null,
  title: string,
  lines: string[],
  height = 36,
  t: PdfTheme = INQUIRY_PDF_THEME,
) {
  const w = doc.internal.pageSize.getWidth();
  doc.setFillColor(t.headerBg);
  doc.rect(0, 0, w, height, "F");
  doc.setFillColor(t.rule);
  doc.rect(0, height, w, 1, "F");

  if (logo) doc.addImage(logo, "PNG", 7.5, (height - 24) / 2, 24, 24);

  const right = w - 8;
  doc.setFont("helvetica", "bold");
  doc.setFontSize(t.pillAccent ? 16 : 20);
  doc.setTextColor(t.title);
  doc.text(title, right, 13, { align: "right" });

  doc.setTextColor(t.text);
  lines.forEach((line, i) => {
    doc.setFont("helvetica", i === 0 && !t.pillAccent ? "bold" : "normal");
    doc.setFontSize(8.5);
    doc.text(line, right, 19 + i * 4.6, { align: "right" });
  });
  return height + 1;
}

export type DetailRow =
  | [label: string, value: string, bold?: boolean]
  | { label: string; image: PdfImage };

const LABEL_W = 67;
const LINE_H = 4.2;

/** Label/value rows with a grey label column (optionally an image row). Returns the y below. */
export function detailRows(
  doc: jsPDF,
  rows: DetailRow[],
  y: number,
  t: PdfTheme = INQUIRY_PDF_THEME,
) {
  const width = doc.internal.pageSize.getWidth() - MARGIN * 2;
  const valueX = MARGIN + LABEL_W;
  const valueW = width - LABEL_W - 6;

  rows.forEach((row) => {
    const isImage = !Array.isArray(row);
    const label = isImage ? row.label : row[0];
    doc.setFontSize(9);

    let h: number;
    let lines: string[] = [];
    if (isImage) {
      h = 40;
    } else {
      doc.setFont("helvetica", row[2] ? "bold" : "normal");
      lines = doc.splitTextToSize(row[1] || "-", valueW);
      h = Math.max(9, lines.length * LINE_H + 4.8);
    }

    doc.setFillColor(t.labelBg);
    doc.rect(MARGIN, y, LABEL_W, h, "F");
    doc.setDrawColor(t.border);
    doc.setLineWidth(0.25);
    doc.line(MARGIN, y + h, MARGIN + width, y + h);

    doc.setTextColor(t.text);
    doc.setFont("helvetica", "bold");
    doc.text(label, MARGIN + 3, y + 5.6);

    if (isImage) {
      // Fit inside a 28 × 34 mm passport-style frame.
      const { image } = row;
      const boxW = 28;
      const boxH = 34;
      const scale = Math.min(boxW / image.width, boxH / image.height);
      const iw = image.width * scale;
      const ih = image.height * scale;
      const bx = valueX + 3;
      const by = y + 3;
      doc.setDrawColor("#CCCCCC");
      doc.setLineWidth(0.3);
      doc.rect(bx - 0.8, by - 0.8, iw + 1.6, ih + 1.6);
      doc.addImage(image.data, "JPEG", bx, by, iw, ih);
    } else {
      doc.setFont("helvetica", row[2] ? "bold" : "normal");
      doc.text(lines, valueX + 3, y + 5.6, { lineHeightFactor: 1.3 });
    }
    y += h;
  });
  return y;
}

/** Full-width highlighted note, e.g. "Special Offer: 12%". Returns the y below. */
export function highlightBox(
  doc: jsPDF,
  label: string,
  value: string,
  y: number,
  t: PdfTheme = INQUIRY_PDF_THEME,
) {
  const width = doc.internal.pageSize.getWidth() - MARGIN * 2;
  doc.setFontSize(9);
  doc.setFont("helvetica", "bold");
  const labelText = `${label}: `;
  const labelW = doc.getTextWidth(labelText);
  doc.setFont("helvetica", "normal");
  const lines: string[] = doc.splitTextToSize(value, width - labelW - 10);
  const h = Math.max(10, lines.length * LINE_H + 5.5);

  doc.setFillColor(t.highlightBg);
  doc.rect(MARGIN, y, width, h, "F");
  doc.setFillColor(t.pillAccent || t.rule);
  doc.rect(MARGIN, y, 1.2, h, "F");

  doc.setTextColor(t.text);
  doc.setFont("helvetica", "bold");
  doc.text(labelText, MARGIN + 4, y + 6.2);
  doc.setFont("helvetica", "normal");
  doc.text(lines, MARGIN + 4 + labelW, y + 6.2, { lineHeightFactor: 1.3 });
  return y + h;
}

/** Signature block (institute name + line), right aligned. */
export function signature(
  doc: jsPDF,
  name: string,
  y: number,
  t: PdfTheme = INQUIRY_PDF_THEME,
) {
  const right = doc.internal.pageSize.getWidth() - MARGIN - 6;
  doc.setFont("helvetica", "normal");
  doc.setFontSize(8);
  doc.setTextColor(t.muted);
  doc.text(name, right, y + 13, { align: "right" });
  doc.setDrawColor(t.text);
  doc.setLineWidth(0.3);
  doc.line(right - 54, y + 22, right, y + 22);
}

/** Long date: "January 13, 2026". */
export function longDate(value?: string | null) {
  if (!value) return "-";
  const [y, m, d] = value.slice(0, 10).split("-").map(Number);
  if (!y || !m || !d) return value;
  return new Date(y, m - 1, d).toLocaleDateString("en-US", {
    month: "long",
    day: "numeric",
    year: "numeric",
  });
}

/** Download a list of rows as a landscape PDF table. */
export async function downloadTablePdf<T>(
  rows: T[],
  columns: ExportColumnLike<T>[],
  opts: {
    title: string;
    subtitle?: string[];
    fileName: string;
    institute?: string;
    theme?: PdfTheme;
  },
) {
  const t = opts.theme || INQUIRY_PDF_THEME;
  const [doc, logo, { autoTable }] = await Promise.all([
    newPdf("landscape"),
    loadLogo(),
    import("jspdf-autotable"),
  ]);
  const name = opts.institute || INSTITUTE_NAME;
  const top = headerBand(
    doc,
    logo,
    name.toUpperCase(),
    [opts.title, ...(opts.subtitle || [])],
    34,
    t,
  );

  autoTable(doc, {
    startY: top + 6,
    margin: { left: 8, right: 8, bottom: 18 },
    head: [columns.map((c) => c.header)],
    body: rows.map((r) => columns.map((c) => String(c.value(r) ?? ""))),
    styles: {
      font: "helvetica",
      fontSize: 8,
      textColor: t.text,
      cellPadding: 2.2,
      lineColor: t.border,
      lineWidth: 0.2,
    },
    headStyles: { fillColor: t.pill, textColor: "#FFFFFF", fontStyle: "bold" },
    alternateRowStyles: { fillColor: t.labelBg },
    didDrawPage: () => footerBand(doc, name, t),
  });

  doc.save(`${opts.fileName}.pdf`);
}
